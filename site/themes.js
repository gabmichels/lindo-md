/**
 * The CSS custom properties one half of one preset resolves to.
 *
 * `accent` defaults to the link, which is what the app does when a palette does
 * not state one, and the alert and syntax families fall back to the shared sets
 * above. Every half writes the same set of keys — a half that only wrote what it
 * changed would leave the previous theme's colors showing through, which is the
 * same trap `apply.ts` documents.
 */
export function tokensFor(theme, appearance) {
  const p = theme[appearance];
  const alerts = (theme.alerts ?? ALERTS)[appearance];
  const code = (theme.code ?? GENERIC_CODE)[appearance];
  return {
    "--bg": p.bg,
    "--surface": p.surface,
    "--text": p.text,
    "--muted": p.muted,
    "--heading": p.heading,
    "--link": p.link,
    "--border": p.border,
    "--code-bg": p.codeBg,
    "--accent": p.accent ?? p.link,
    "--note": alerts.note,
    "--tip": alerts.tip,
    "--important": alerts.important,
    "--warning": alerts.warning,
    "--caution": alerts.caution,
    "--c-comment": code.comment,
    "--c-string": code.string,
    "--c-keyword": code.keyword,
    "--c-func": code.func,
    "--c-constant": code.constant,
    "--c-type": code.type,
    "--c-punct": code.punct,
  };
}
